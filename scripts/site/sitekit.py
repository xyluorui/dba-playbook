# ── 链接改写 ──────────────────────────────────────────────

def rewrite_href(href: str) -> str:
    """把 Markdown 语境的链接改写成 HTML 站点语境。

    - README.md      → index.html（目录导航页）
    - 内容 *.md      → *.html
    - AGENTS.md / CONTRIBUTING.md / templates/*.md → 保持 .md（规范文档原样发布）
    - 目录链接 xxx/  → xxx/index.html
    - 外链 / 锚点    → 原样
    """
    if not href:
        return href
    if re.match(r"^(https?:|mailto:|data:|#)", href):
        return href
    path, sep, frag = href.partition("#")
    if not path:
        return href
    norm = path.replace("\\", "/")
    if norm.startswith("/"):
        # 根路径引用在 GitHub Pages 子路径下会断，原样返回（由 --check 报错）
        return href
    lower = norm.lower()
    if lower.endswith(".md"):
        base = os.path.basename(norm)
        if base == "README.md":
            parent = os.path.dirname(norm)
            new = (parent + "/" if parent else "") + "index.html"
        elif base in KEPT_MD_NAMES or norm.startswith("templates/"):
            return href
        else:
            new = norm[:-3] + ".html"
    elif norm.endswith("/"):
        new = norm + "index.html"
    else:
        return href
    return new + (sep + frag if sep else "")


# ── 行内 Markdown ─────────────────────────────────────────

_CODE_SPAN = re.compile(r"`([^`]+)`")
_LINK = re.compile(r"\[([^\]]+)\]\(([^)\s]+)\)")
_BOLD = re.compile(r"\*\*([^*]+)\*\*")


def inline(text: str, allow_links: bool = True) -> str:
    """行内 Markdown → HTML。"""
    codes: list = []

    def _stash(m):
        # 表格单元格里的 \| 是转义竖线，代码段内同样还原
        codes.append(m.group(1).replace("\\|", "|"))
        return "\x00%d\x00" % (len(codes) - 1)

    text = _CODE_SPAN.sub(_stash, text)
    text = _html.escape(text, quote=False)

    if allow_links:
        def _link(m):
            label = inline(m.group(1), allow_links=False)
            href = _html.escape(rewrite_href(m.group(2)), quote=True)
            return '<a href="%s">%s</a>' % (href, label)

        text = _LINK.sub(_link, text)

    text = _BOLD.sub(r"<strong>\1</strong>", text)
    text = text.replace("\\|", "|")

    def _restore(m):
        return "<code>%s</code>" % _html.escape(codes[int(m.group(1))], quote=False)

    return re.sub(r"\x00(\d+)\x00", _restore, text)


# ── 块级 Markdown ─────────────────────────────────────────

_HEADING = re.compile(r"^(#{1,6})\s+(.*)$")
_FENCE = re.compile(r"^```(\S*)\s*$")
_UL_ITEM = re.compile(r"^(\s*)([-*+])\s+(.*)$")
_OL_ITEM = re.compile(r"^(\s*)(\d+)[.)]\s+(.*)$")
_HR = re.compile(r"^(-{3,}|\*{3,}|_{3,})\s*$")
_TABLE_SEP = re.compile(r"^\s*\|?\s*:?-{2,}:?\s*(\|\s*:?-{2,}:?\s*)*\|?\s*$")


def split_row(line: str) -> list:
    """按未转义的 | 切分表格行。"""
    s = line.strip()
    if s.startswith("|"):
        s = s[1:]
    if s.endswith("|") and not s.endswith("\\|"):
        s = s[:-1]
    return [c.strip() for c in re.split(r"(?<!\\)\|", s)]


def _is_block_start(line: str) -> bool:
    if not line.strip():
        return False
    return bool(
        _HEADING.match(line)
        or _FENCE.match(line.strip())
        or _UL_ITEM.match(line)
        or _OL_ITEM.match(line)
        or _HR.match(line.strip())
        or line.strip().startswith(">")
        or "|" in line
    )


def _parse_list_items(lines: list, i: int):
    """把列表区域解析成扁平的 (缩进, 是否有序, 文本) 列表，返回 (items, next_index)。"""
    items: list = []
    while i < len(lines):
        line = lines[i]
        if not line.strip():
            nxt = lines[i + 1] if i + 1 < len(lines) else ""
            if _UL_ITEM.match(nxt) or _OL_ITEM.match(nxt):
                i += 1
                continue
            break
        m = _UL_ITEM.match(line) or _OL_ITEM.match(line)
        if m:
            items.append((len(m.group(1)), bool(_OL_ITEM.match(line)), m.group(3)))
            i += 1
            continue
        if items and line.startswith(" "):
            indent, ordered, text = items[-1]
            items[-1] = (indent, ordered, text + " " + line.strip())
            i += 1
            continue
        break
    return items, i


def _build_list(items: list, idx: int, indent: int):
    """按缩进递归构建一层 <ul>/<ol>，返回 (html, next_index)。"""
    ordered = items[idx][1]
    tag = "ol" if ordered else "ul"
    li_chunks: list = []  # 每个元素是该 <li> 内的 html 片段列表
    i = idx
    while i < len(items):
        item_indent, item_ordered, text = items[i]
        if item_indent < indent:
            break
        if item_indent > indent:
            if li_chunks:
                nested, i = _build_list(items, i, item_indent)
                li_chunks[-1].append(nested)
            else:
                i += 1
            continue
        if item_ordered != ordered:
            break
        li_chunks.append([inline(text)])
        i += 1
    lis = "\n".join("<li>%s</li>" % "".join(ch) for ch in li_chunks)
    return "<%s>\n%s\n</%s>" % (tag, lis, tag), i


def _render_list(lines: list, i: int):
    """渲染列表（支持按缩进嵌套），返回 (html, next_index)。"""
    items, i = _parse_list_items(lines, i)
    if not items:
        return "", i
    parts = []
    idx = 0
    while idx < len(items):
        html, idx = _build_list(items, idx, items[idx][0])
        parts.append(html)
    return "\n".join(parts), i


def render_md(md_text: str, skip_h1: bool = False) -> str:
    """Markdown 子集 → HTML 片段。"""
    lines = md_text.replace("\r\n", "\n").split("\n")
    out: list = []
    i = 0
    skipped_h1 = not skip_h1

    while i < len(lines):
        line = lines[i]
        if not line.strip():
            i += 1
            continue

        m = _FENCE.match(line.strip())
        if m:
            lang = m.group(1)
            i += 1
            buf = []
            while i < len(lines) and lines[i].strip() != "```":
                buf.append(lines[i])
                i += 1
            i += 1  # 跳过收尾 ```
            content = _html.escape("\n".join(buf), quote=False)
            if lang == "mermaid":
                out.append('<pre class="mermaid">%s</pre>' % content)
            else:
                cls = ' class="language-%s"' % _html.escape(lang, quote=True) if lang else ""
                out.append("<pre><code%s>%s</code></pre>" % (cls, content))
            continue

        m = _HEADING.match(line)
        if m:
            level = len(m.group(1))
            if level == 1 and not skipped_h1:
                skipped_h1 = True
                i += 1
                continue
            out.append("<h%d>%s</h%d>" % (level, inline(m.group(2)), level))
            i += 1
            continue

        if _HR.match(line.strip()):
            out.append("<hr>")
            i += 1
            continue

        if line.strip().startswith(">"):
            buf = []
            while i < len(lines) and lines[i].strip().startswith(">"):
                buf.append(re.sub(r"^\s*>\s?", "", lines[i]))
                i += 1
            inner = render_md("\n".join(buf))
            out.append("<blockquote>\n%s\n</blockquote>" % inner)
            continue

        if "|" in line and i + 1 < len(lines) and _TABLE_SEP.match(lines[i + 1]):
            header = split_row(line)
            i += 2
            rows = []
            while i < len(lines) and lines[i].strip() and "|" in lines[i]:
                rows.append(split_row(lines[i]))
                i += 1
            thead = "<tr>" + "".join("<th>%s</th>" % inline(c) for c in header) + "</tr>"
            tbody = "\n".join(
                "<tr>" + "".join("<td>%s</td>" % inline(c) for c in row) + "</tr>" for row in rows
            )
            out.append(
                '<div class="table-wrap"><table>\n<thead>%s</thead>\n<tbody>%s</tbody>\n</table></div>'
                % (thead, tbody)
            )
            continue

        if _UL_ITEM.match(line) or _OL_ITEM.match(line):
            html, i = _render_list(lines, i)
            if html:
                out.append(html)
            continue

        # 段落：连续普通行合并
        buf = [line.strip()]
        i += 1
        while i < len(lines) and lines[i].strip() and not _is_block_start(lines[i]):
            buf.append(lines[i].strip())
            i += 1
        out.append("<p>%s</p>" % inline(" ".join(buf)))

    return "\n".join(out)


# ── Front matter / HTML 元信息 ────────────────────────────

def parse_front_matter(text: str):
    """解析文首 YAML front matter（简单 key: value 子集），返回 (meta, body)。"""
    meta: dict = {}
    lines = text.replace("\r\n", "\n").split("\n")
    if not lines or lines[0].strip() != "---":
        return meta, text
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            body = "\n".join(lines[i + 1:])
            return meta, body.lstrip("\n")
        m = re.match(r"^([A-Za-z_][\w-]*)\s*:\s*(.*)$", lines[i])
        if m:
            val = m.group(2).strip()
            val = re.sub(r"^<!--|-->$", "", val).strip()
            if val.startswith("[") and val.endswith("]"):
                val = ", ".join(v.strip().strip("'\"") for v in val[1:-1].split(",") if v.strip())
            meta[m.group(1)] = val
    return meta, text


_META_TAG = re.compile(r'<meta\s+name="([^"]+)"\s+content="([^"]*)"', re.I)
_TITLE_TAG = re.compile(r"<title>(.*?)</title>", re.S | re.I)
_H1_TAG = re.compile(r"<h1[^>]*>(.*?)</h1>", re.S | re.I)


def extract_html_meta(html_text: str) -> dict:
    return {m.group(1).lower(): m.group(2) for m in _META_TAG.finditer(html_text)}


def extract_html_title(html_text: str, fallback: str = "") -> str:
    m = _TITLE_TAG.search(html_text)
    if m:
        t = re.sub(r"\s*\|\s*%s\s*$" % re.escape(SITE_NAME), "", m.group(1)).strip()
        if t:
            return t
    m = _H1_TAG.search(html_text)
    if m:
        return re.sub(r"<[^>]+>", "", m.group(1)).strip()
    return fallback


class _TextExtractor(HTMLParser):
    SKIP = {"script", "style", "nav", "header", "footer"}
    VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input",
            "link", "meta", "param", "source", "track", "wbr"}

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.parts: list = []
        self._skip_stack: list = []  # 每层记录该标签是否"压栈跳过"

    def handle_starttag(self, tag, attrs):
        if tag in self.VOID:
            return
        skip = tag in self.SKIP or (tag == "pre" and ("class", "mermaid") in attrs)
        self._skip_stack.append(skip)

    def handle_endtag(self, tag):
        if tag not in self.VOID and self._skip_stack:
            self._skip_stack.pop()

    def handle_data(self, data):
        if not any(self._skip_stack):
            self.parts.append(data)


def html_to_text(html_text: str) -> str:
    """HTML → 纯文本（用于搜索索引）。"""
    p = _TextExtractor()
    try:
        p.feed(html_text)
    except Exception:
        pass
    return re.sub(r"\s+", " ", "".join(p.parts)).strip()


