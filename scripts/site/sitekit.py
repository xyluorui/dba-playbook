def sync_shell(html_text: str):
    """把页面里的标记块（兜底样式/外壳头/外壳尾）刷新为 sitekit 当前版本。

    返回 (新文本, 缺失的标记块名列表)。root 取自 <body data-root>。
    """
    m = _BODY_ROOT.search(html_text)
    root = m.group(1) if m else ""
    missing = []
    for name, (pat, make) in zip(("fallback-style", "shell:top", "shell:bottom"), _SHELL_REGIONS):
        if pat.search(html_text):
            html_text = pat.sub(lambda _m, make=make: make(root), html_text, count=1)
        else:
            missing.append(name)
    # 元信息还是 {{占位符}} 的模板不生成页头徽章/目录（new-doc.py 填值后再同步）
    is_template = extract_html_meta(html_text).get("database", "").startswith("{{")
    return decorate(html_text, with_head=not is_template), missing


META_ORDER = ["database", "category", "tags", "date", "status"]


def wrap_page(title: str, root: str, body: str, meta: dict = None,
              breadcrumb_html: str = "") -> str:
    """把正文包进统一页面骨架。

    title: 页面标题（进 <title>，正文里自行放 <h1>）
    root:  到站点根的相对前缀（如 ""、"../"、"../../"）
    meta:  元信息 dict → <meta> 标签；徽章行由 ui.js 渲染
    """
    meta = meta or {}
    meta_tags = ""
    for key in META_ORDER:
        if key in meta and meta[key]:
            meta_tags += '\n<meta name="%s" content="%s">' % (
                _html.escape(key, quote=True), _html.escape(str(meta[key]), quote=True))
    for key, val in meta.items():
        if key not in META_ORDER and val:
            meta_tags += '\n<meta name="%s" content="%s">' % (
                _html.escape(key, quote=True), _html.escape(str(val), quote=True))
    breadcrumb = ('    %s\n' % breadcrumb_html) if breadcrumb_html else ""
    return PAGE_SHELL.format(
        title=_html.escape(title, quote=False),
        site_name=SITE_NAME,
        meta_tags=meta_tags,
        root=root,
        shell_top=render_shell(SHELL_TOP, root),
        shell_bottom=render_shell(SHELL_BOTTOM, root),
        breadcrumb=breadcrumb,
        fallback_style=FALLBACK_STYLE_BLOCK,
        body=body.rstrip("\n"),
    )


def root_prefix(rel_path: str) -> str:
    """文件相对站点根的 ../ 前缀。rel_path 用 / 分隔，相对仓库根。"""
    depth = rel_path.count("/")
    return "../" * depth


