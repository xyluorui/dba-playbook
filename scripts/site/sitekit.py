def render_meta_badges(meta: dict) -> str:
    """与 ui.js 旧 renderMeta 同一规则：database/category/tags/date/status → 徽章。"""
    h = ""
    meta = {k: ("" if "填写" in v else v) for k, v in meta.items()}
    if meta.get("database"):
        h += '<span class="badge db">%s</span>' % _html.escape(meta["database"])
    if meta.get("category"):
        h += '<span class="badge cat">%s</span>' % _html.escape(meta["category"])
    for tag in re.split(r"[,，]", meta.get("tags", "")):
        tag = tag.strip()
        if tag and "填写" not in tag:
            h += '<span class="badge">%s</span>' % _html.escape(tag)
    if meta.get("date"):
        h += '<span class="badge">%s</span>' % _html.escape(meta["date"])
    if meta.get("status"):
        st = re.split(r"[,，\s]", meta["status"])[0].lower()
        h += '<span class="badge status-%s">%s</span>' % (
            _html.escape(st), _html.escape(meta["status"]))
    return h


def _plain(inner_html: str) -> str:
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", inner_html)).strip()


def _add_heading_ids(article: str):
    """给没有 id 的 h2/h3 补 sec-N（与 ui.js 编号规则一致），返回 (新正文, [(level, id, 文本)])。"""
    heads, counter = [], [0]

    def repl(m):
        counter[0] += 1
        level, attrs, inner = m.group(1), m.group(2), m.group(3)
        idm = re.search(r'\sid="([^"]+)"', attrs)
        hid = idm.group(1) if idm else "sec-%d" % counter[0]
        if not idm:
            attrs = ' id="%s"%s' % (hid, attrs)
        heads.append((level, hid, _plain(inner)))
        return "<h%s%s>%s</h%s>" % (level, attrs, inner, level)

    return _HEADING_TAG.sub(repl, article), heads


def _toc_html(heads) -> str:
    if len(heads) < 3:
        return ""
    items = "\n".join(
        '<li class="h%s"><a href="#%s">%s</a></li>' % (lv, hid, _html.escape(text, quote=False))
        for lv, hid, text in heads)
    opened = " open" if len(heads) <= 10 else ""
    return ('<nav class="toc-inline" aria-label="本文目录"><details%s><summary>本文目录（%d 节）</summary>\n'
            '<ul>\n%s\n</ul></details></nav>' % (opened, len(heads), items))


_HL_STATE = {"ok": None}


def _highlight_many(items):
    """[(lang, code)] → [html|None]；Node 不可用时全部 None（浏览器端由 ui.js 兜底）。"""
    if not items or _HL_STATE["ok"] is False:
        return [None] * len(items)
    node = _shutil.which("node")
    script = os.path.join(os.path.dirname(os.path.abspath(__file__)), "highlight.js")
    if not node:
        _HL_STATE["ok"] = False
        return [None] * len(items)
    try:
        r = _subprocess.run(
            [node, script], input=_json.dumps([{"lang": l, "code": c} for l, c in items]),
            capture_output=True, text=True, encoding="utf-8", timeout=60)
        if r.returncode != 0:
            raise RuntimeError(r.stderr)
        _HL_STATE["ok"] = True
        return _json.loads(r.stdout)
    except Exception:
        _HL_STATE["ok"] = False
        return [None] * len(items)


def _code_source(inner_html: str) -> str:
    """代码块 innerHTML → 源码文本：先剥高亮 <span>，再还原实体（源码里的 < > 已被转义，不会被误剥）。"""
    return _html.unescape(_SPAN_TAG.sub("", inner_html))


def fix_svg_compat(text: str) -> str:
    """SVG <text> 的 dominant-baseline 属性 → style（Obsidian 插件属性白名单会剥掉前者）。"""
    return _SVG_TEXT.sub(_fix_svg_text, text)


def _fix_svg_text(m) -> str:
    """dominant-baseline 属性会被 Obsidian 插件的属性白名单剥掉，挪进 style（白名单允许）。"""
    tag = m.group(0)
    dm = re.search(r'\sdominant-baseline="([^"]*)"', tag)
    tag = tag.replace(dm.group(0), "", 1)
    decl = "dominant-baseline: %s;" % dm.group(1)
    sm = re.search(r'\sstyle="([^"]*)"', tag)
    if sm:
        body = sm.group(1).rstrip()
        sep = "" if body.endswith(";") or not body else ";"
        return tag.replace(sm.group(0), ' style="%s%s %s"' % (body, sep, decl), 1)
    return tag[:-1] + ' style="%s">' % decl


def decorate(html_text: str, with_head: bool = True) -> str:
    """手写内容页的构建期装饰（幂等）。with_head=False 用于模板（元信息是占位符）。"""
    html_text = fix_svg_compat(html_text)

    m = _ARTICLE.search(html_text)
    if not m:
        return html_text
    article = m.group(2)

    # 代码高亮
    blocks = list(_CODE_BLOCK.finditer(article))
    if blocks:
        results = _highlight_many([(b.group(1), _code_source(b.group(2))) for b in blocks])
        out, last = [], 0
        for b, hl in zip(blocks, results):
            out.append(article[last:b.start()])
            if hl is None:
                out.append(b.group(0))
            else:
                out.append('<pre><code class="language-%s hljs">%s</code></pre>' % (b.group(1), hl))
            last = b.end()
        out.append(article[last:])
        article = "".join(out)

    # 页头：元信息徽章 + 页内目录
    article = _PAGE_HEAD.sub("", article)
    article, heads = _add_heading_ids(article)
    if with_head:
        meta = extract_html_meta(html_text)
        head_html = ""
        badges = render_meta_badges(meta)
        if badges:
            head_html += '<p class="meta">%s</p>\n' % badges
        head_html += _toc_html(heads)
        h1 = _H1_END.search(article)
        if head_html and h1:
            block = ("<!-- page-head:start（同步工具：scripts/site/sync-shell.py） -->\n"
                     + head_html.rstrip("\n") + "\n<!-- page-head:end -->\n")
            article = article[:h1.end()] + ("" if article[:h1.end()].endswith("\n") else "\n") + block + article[h1.end():]

    return html_text[:m.start(2)] + article + html_text[m.end(2):]
